test('project filters distinguish status from archive state', async ({ page }) => {
  await login(page)
  for (const [name, status, archived] of [['Idea example', 0, false], ['Active example', 1, false], ['Archived example', 1, true]]) {
    const created = await page.request.post('/api/projects', { data: { name } })
    expect(created.status()).toBe(201)
    const project = await created.json()
    expect((await page.request.patch(`/api/projects/${project.projectId}`, { data: { projectStatus: status } })).status()).toBe(200)
    if (archived) expect((await page.request.post(`/api/projects/${project.projectId}/archive`)).status()).toBe(204)
  }
  await page.reload()
  await expect(page.locator('.project-card')).toHaveCount(3)
  await page.getByRole('combobox', { name: 'Project status', exact: true }).selectOption('active')
  await expect(page.locator('.project-card')).toHaveCount(1)
  await expect(page.locator('.project-card')).toContainText('Active example')
  await page.getByRole('combobox', { name: 'Project status', exact: true }).selectOption('archived')
  await expect(page.locator('.project-card')).toHaveCount(1)
  await expect(page.locator('.project-card')).toContainText('Archived example')
  await page.getByRole('combobox', { name: 'Project status', exact: true }).selectOption('')
  await page.getByLabel('Search projects', { exact: true }).fill('idea')
  await expect(page.locator('.project-card')).toHaveCount(1)
  await expect(page.locator('.project-card')).toContainText('Idea example')
})
