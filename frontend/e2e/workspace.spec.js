import { test, expect } from '@playwright/test'
const password = 'Browser-Test-42!'
async function login(page) {
  const email = `${crypto.randomUUID()}@example.com`
  const response = await page.request.post('/api/auth/register', { data: { email, nickname: 'Browser tester', password } })
  expect(response.status()).toBe(201)
  await page.goto('/login'); await page.getByLabel('E-mail', { exact: true }).fill(email); await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click(); await expect(page.getByRole('heading', { name: 'My projects', level: 1 })).toBeVisible()
}
async function project(page, name) {
  await page.getByRole('button', { name: 'New project', exact: true }).click()
  await page.getByLabel('Project name').fill(name); await page.getByRole('button', { name: 'Save project' }).click()
  await page.getByRole('link', { name: new RegExp(name) }).last().click()
  await expect(page).toHaveURL(/\/projects\/[0-9a-f-]+$/)
  await expect(page.getByRole('heading', { name, exact: true, level: 1 })).toBeVisible()
}
